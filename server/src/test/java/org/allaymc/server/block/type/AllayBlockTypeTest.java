package org.allaymc.server.block.type;

import org.allaymc.api.block.property.enums.WallConnectionType;
import org.allaymc.api.block.property.type.BlockPropertyType;
import org.allaymc.api.block.property.type.BlockPropertyTypes;
import org.allaymc.api.block.type.BlockType;
import org.allaymc.server.item.type.AllayItemType;
import org.allaymc.testutils.AllayTestExtension;
import org.allaymc.testutils.TestRegistryFixtures;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;

import static org.allaymc.api.block.type.BlockTypes.BLUE_CANDLE;
import static org.allaymc.api.block.type.BlockTypes.COBBLED_DEEPSLATE_WALL;
import static org.allaymc.server.block.type.AllayBlockType.computeSpecialValue;
import static org.junit.jupiter.api.Assertions.*;

/**
 * {@code AllayBlockTypeTest} verifies fixture block types, canonical states,
 * attributes, and packed identifiers.
 *
 * @author daoge_cmd
 */
@ExtendWith(AllayTestExtension.class)
class AllayBlockTypeTest {
    // testBlockType1 and testBlockType2 are the fixture types initialized before
    // tests. Their behavior and item lookups share the fixture registry lifetime.
    /**
     * First registered fixture block.
     */
    static BlockType<TestBlock> testBlockType1;
    /**
     * Second registered fixture block.
     */
    static BlockType<TestBlock> testBlockType2;
    // TEST_BOOLEAN_PROPERTY_TYPE, TEST_INT_PROPERTY_TYPE, and
    // TEST_ENUM_PROPERTY_TYPE are the exact fixture property instances. State
    // access uses their identities rather than matching names alone.
    /**
     * Fixture boolean property domain.
     */
    static BlockPropertyType<Boolean> TEST_BOOLEAN_PROPERTY_TYPE;
    /**
     * Fixture integer property domain.
     */
    static BlockPropertyType<Integer> TEST_INT_PROPERTY_TYPE;
    /**
     * Fixture enum property domain.
     */
    static BlockPropertyType<TestEnum> TEST_ENUM_PROPERTY_TYPE;

    /**
     * Resolves the shared block and property fixtures after server test
     * initialization.
     */
    @BeforeAll
    static void init() {
        TEST_BOOLEAN_PROPERTY_TYPE = TestRegistryFixtures.blockBooleanProperty();
        TEST_INT_PROPERTY_TYPE = TestRegistryFixtures.blockIntProperty();
        TEST_ENUM_PROPERTY_TYPE = TestRegistryFixtures.blockEnumProperty();
        testBlockType1 = TestRegistryFixtures.blockType1();
        testBlockType2 = TestRegistryFixtures.blockType2();
    }

    /**
     * Reads the two fixture blocks after registration. Each block must expose an
     * associated item type so block-to-item conversion can use the item registry
     * entry.
     */
    @Test
    void testDefaultItemType() {
        assertNotNull(testBlockType1.getItemType());
        assertNotNull(testBlockType2.getItemType());
    }

    /**
     * Reads the item associated with a fixture whose automatic item builder
     * received a customizer. The generated item must retain the custom tag
     * installed before item registration.
     */
    @Test
    void testCustomizeAutoGeneratedItemType() {
        var customTag = TestRegistryFixtures.customizedItemTag();
        var blockType = TestRegistryFixtures.customizedItemBlockType();

        assertNotNull(blockType.getItemType());
        assertTrue(blockType.getItemType().hasItemTag(customTag));
    }

    /**
     * Inspects a constant-definition fixture and an ordinary fixture without a
     * custom definition. Every constructed state must receive the constant block
     * definition, while absent block and item definitions remain absent.
     */
    @Test
    void testConstantAndMissingCustomDefinitions() {
        var constantBlock = (AllayBlockType<?>) TestRegistryFixtures.customizedItemBlockType();
        var definition = constantBlock.getCustomBlockDefinition();

        assertNotNull(definition);
        assertEquals(constantBlock.getAllStates().size(), definition.stateDefinitions().size());
        assertEquals(1, definition.stateDefinitions().values().stream().distinct().count());
        assertNull(((AllayItemType<?>) constantBlock.getItemType()).getCustomItemDefinition());
        assertNull(((AllayBlockType<?>) testBlockType1).getCustomBlockDefinition());
    }

    /**
     * Reads the first registered custom-block fixture after extension
     * initialization. The fixture must be available so the remaining state and
     * behavior checks operate on a constructed type.
     */
    @Test
    void testBlockType() {
        assertNotNull(testBlockType1);
    }

    /**
     * Updates boolean, integer, and enum properties through the fixture behavior
     * and default state. Each returned state must expose the requested value while
     * retaining access to the owning block type.
     */
    @Test
    void testCommon() {
        var block = testBlockType1.getBlockBehavior();
        assertEquals(testBlockType1, block.getBlockType());
        var state = block.getBlockType().getDefaultState();
        assertFalse(state.getPropertyValue(TEST_BOOLEAN_PROPERTY_TYPE));
        state = state.setPropertyValue(TEST_BOOLEAN_PROPERTY_TYPE, true);
        assertTrue(state.getPropertyValue(TEST_BOOLEAN_PROPERTY_TYPE));
        assertEquals(0, state.getPropertyValue(TEST_INT_PROPERTY_TYPE));
        state = state.setPropertyValue(TEST_INT_PROPERTY_TYPE, 5);
        assertEquals(5, state.getPropertyValue(TEST_INT_PROPERTY_TYPE));
        assertEquals(TestEnum.A, state.getPropertyValue(TEST_ENUM_PROPERTY_TYPE));
        state = state.setPropertyValue(TEST_ENUM_PROPERTY_TYPE, TestEnum.B);
        assertEquals(TestEnum.B, state.getPropertyValue(TEST_ENUM_PROPERTY_TYPE));
    }

    /**
     * Builds specific wall and candle property combinations and reads their
     * unsigned state hashes. The expected numeric hashes protect the serialized
     * property encoding used by those registered states.
     */
    @Test
    void testBlockStateHash() {
        var b1 = COBBLED_DEEPSLATE_WALL.getDefaultState();
        b1 = b1.setPropertyValue(BlockPropertyTypes.WALL_CONNECTION_TYPE_EAST, WallConnectionType.NONE);
        b1 = b1.setPropertyValue(BlockPropertyTypes.WALL_CONNECTION_TYPE_NORTH, WallConnectionType.TALL);
        b1 = b1.setPropertyValue(BlockPropertyTypes.WALL_CONNECTION_TYPE_SOUTH, WallConnectionType.SHORT);
        b1 = b1.setPropertyValue(BlockPropertyTypes.WALL_CONNECTION_TYPE_WEST, WallConnectionType.NONE);
        b1 = b1.setPropertyValue(BlockPropertyTypes.WALL_POST_BIT, true);
        assertEquals(1789459903, b1.unsignedBlockStateHash());

        var b2 = BLUE_CANDLE.getDefaultState();
        b2 = b2.setPropertyValue(BlockPropertyTypes.CANDLES, 2);
        b2 = b2.setPropertyValue(BlockPropertyTypes.LIT, false);
        assertEquals(4220034033L, b2.unsignedBlockStateHash());
    }

    /**
     * Reads state metadata from the two fixture block behaviors. Their distinct
     * configured burn odds must survive component assembly and be returned for each
     * type's default state.
     */
    @Test
    void testBlockAttributes() {
        assertEquals(2, testBlockType1.getBlockBehavior().getBlockStateData(testBlockType1.getDefaultState()).burnOdds());
        assertEquals(3, testBlockType2.getBlockBehavior().getBlockStateData(testBlockType2.getDefaultState()).burnOdds());
    }

    /**
     * Packs boolean, integer, and enum indices using their combined declared bit
     * widths. Changing one wrapped value must change only its expected portion of
     * the resulting packed state key.
     */
    @Test
    void testSpecialValue() {
        var values = new BlockPropertyType.BlockPropertyValue<?, ?, ?>[3];
        values[0] = (TEST_BOOLEAN_PROPERTY_TYPE.createValue(true));// 1 bit
        values[1] = (TEST_INT_PROPERTY_TYPE.createValue(5));// 4 bit
        values[2] = (TEST_ENUM_PROPERTY_TYPE.createValue(TestEnum.B));// 2 bit
        byte offset = 0;
        for (var value : values) {
            offset += value.getPropertyType().getBitSize();
        }
        // The boolean index precedes the four-bit integer and two-bit enum index,
        // preserving their separate packed positions.
        assertEquals(0b1010101, computeSpecialValue(offset, values));
        values[2] = TEST_ENUM_PROPERTY_TYPE.createValue(TestEnum.A);
        assertEquals(0b1010100, computeSpecialValue(offset, values));
        values[1] = TEST_INT_PROPERTY_TYPE.createValue(0);
        assertEquals(0b1000000, computeSpecialValue(offset, values));
    }

}
