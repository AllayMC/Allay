package org.allaymc.api.bossbar;

/**
 * {@code BossBarColor} identifies the client color used for a boss bar. A bar stores one selected
 * color, and viewers use that selection when displaying or refreshing its appearance. These values
 * describe colors rather than separate bar instances.
 *
 * @author daoge_cmd
 */
public enum BossBarColor {
    /**
     * pink boss bar color.
     */
    PINK,
    /**
     * blue boss bar color.
     */
    BLUE,
    /**
     * red boss bar color.
     */
    RED,
    /**
     * green boss bar color.
     */
    GREEN,
    /**
     * yellow boss bar color.
     */
    YELLOW,
    /**
     * purple boss bar color.
     */
    PURPLE,
    /**
     * rebecca purple boss bar color.
     */
    REBECCA_PURPLE,
    /**
     * white boss bar color.
     */
    WHITE
}
